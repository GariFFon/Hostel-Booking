"use client";
import * as React from "react";
import { Avatar as AvatarPrimitive } from "radix-ui";
import { cn } from "@/lib/utils";
import { initials } from "@/lib/format";

/** Image with an initials fallback (also used when the image fails to load). Never squishes: fixed size, shrink-0. */
export function Avatar({ src, name, className, ...props }: { src?: string | null; name?: string | null } & React.ComponentProps<typeof AvatarPrimitive.Root>) {
  return (
    <AvatarPrimitive.Root className={cn("relative flex size-9 shrink-0 overflow-hidden rounded-full bg-accent", className)} {...props}>
      {src ? <AvatarPrimitive.Image src={src} alt="" className="aspect-square size-full object-cover" /> : null}
      <AvatarPrimitive.Fallback aria-hidden className="flex size-full items-center justify-center text-[0.8em] font-semibold text-accent-foreground" delayMs={src ? 300 : 0}>
        {/* Generated by CSS: the initials are decoration, so they are not text a control's accessible name has to include. */}
        <span aria-hidden data-i={initials(name)} className="before:content-[attr(data-i)]" />
      </AvatarPrimitive.Fallback>
    </AvatarPrimitive.Root>
  );
}
